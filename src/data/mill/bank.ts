function subj(id: string): SubjectId {
  if (id.startsWith("chem-")) return "chemistry";
  if (id.startsWith("math-")) return "maths";
  return "physics";
}

function from(id: string, i: number, rows: readonly Row[]): PlayItem {
  const r = rows[i % rows.length]!;
  return mcq({
    chapterId: id,
    i,
    subject: subj(id),
    stem: r[0],
    correct: r[1],
    wrong: [r[2], r[3], r[4]],
    why: r[5],
    tags: ["concept"],
  });
}

