export function bankItem(chapterId: string, i: number): PlayItem | null {
  const rows = [...(BANK[chapterId] ?? []), ...(PLUS[chapterId] ?? [])];
  if (!rows.length) return null;
  return from(chapterId, i, rows);
}

export function bankCoverage() {
  const missing = Object.keys(BANK).filter((k) => !BANK[k]?.length);
  return { chapters: Object.keys(BANK).length, missing };
}
