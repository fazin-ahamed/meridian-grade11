export const CHAPTER_BY_ID: Record<string, ChapterMeta> = Object.fromEntries(
  CATALOG.map((c) => [c.id, c]),
);

export function chaptersBySubject(subject: ChapterMeta["subject"]) {
  return CATALOG.filter((c) => c.subject === subject);
}

export function searchCatalog(q: string) {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return CATALOG.filter((c) => {
    const off = officialFor(c.id);
    const officialBlob = off
      ? `${off.unit} ${off.bullets.join(" ")} ${off.jeeExtra.join(" ")}`
      : "";
    const blob = `${c.title} ${c.unit} ${c.summary} ${c.tags.join(" ")} ${c.ncert} ${officialBlob}`.toLowerCase();
    return blob.includes(s);
  });
}
