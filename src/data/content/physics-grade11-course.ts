import type {
  ChapterContent,
  MasteryLevel,
  MasteryModule,
  MasteryQuestion,
  MasterySection,
} from "../types";

function S(
  id: string,
  title: string,
  body: string,
  bullets?: string[],
  diagram?: string,
): MasterySection {
  return { id, title, body, bullets, diagram };
}

function Q(
  id: string,
  section: string,
  level: MasteryLevel,
  prompt: string,
  choices: string[],
  answer: number,
  explanation: string,
): MasteryQuestion {
  return { id, section, level, prompt, choices, answer, explanation };
}

function M(
  id: string,
  title: string,
  summary: string,
  sections: MasterySection[],
  questions: MasteryQuestion[],
): MasteryModule {
  return { id, title, summary, sections, questions };
}

